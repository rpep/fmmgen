def generate_M_operators(order, symbols, M_dict):
    """
    generate_M_operators(order, symbols, index_dict):

    Generates multipole operators up to order.

    Input:
    order, int:
        Maximum order of multipole expansion

    symbols, list:
        List of sympy symbol type objects which
        define coordinate labels.

    index_dict:
        Forward mapping dictionary between
        monomials of symbols and array indices,
        generated by generate_mappings or otherwise.

    Output:
    list:
        List of symbolic multipole moments up to order.

    Example:
    >>> order = 2
    >>> x, y, z = sp.symbols('x y z')
    >>> map, _ = generate_mappings(order, [x, y, z])
    >>> generate_M_operators(order, (x, y, z), map)
    [q, -q*x, -q*y, -q*z, q*x**2/2, q*x*y, q*x*z, q*y**2/2, q*y*z, q*z**2/2]
    """
    x, y, z = symbols
    M_operators = []
    for n in M_dict.keys():
        M_operators.append(M(n, symbols))
    return M_operators


def generate_S2M_operators(order, symbols, M_dict, source_order=0):
    """Source-to-multipole: the multipole of one point source about a centre.

    Replaces the previous arrangement, in which the driver seeded a scratch
    multipole array with the source's raw moments and then called the general
    M2M to shift it to the cell centre. That worked only because a point
    source's multipole coefficients ARE its moments in this basis -- an
    undocumented basis assumption living in the driver rather than the
    operators -- and it paid for a full M2M when almost every input coefficient
    is known to be zero.

    A source of order s has a multipole supported only on the |n| = s shell, so
    this specialises M_shift to that sparse input:

        S2M_n = sum_{k : |n-k| = s} S[n-k] (x, y, z)^k / k!

    Sign convention follows M2M, i.e. (x, y, z) = centre - source, which is what
    the driver already passes. Note the old P2M used the opposite convention.
    """
    shell = [n for n in M_dict if sum(n) == source_order]
    source_size = len(shell)
    M = sp.MatrixSymbol("M", Nterms(order), 1)
    S = sp.MatrixSymbol("S", source_size, 1)

    subs = {M[M_dict[n]]: 0 for n in M_dict}
    for n in shell:
        # the |n| = s shell occupies the first source_size slots of M_dict, so
        # its index doubles as the index into the caller's S array
        subs[M[M_dict[n]]] = S[M_dict[n]]

    # xreplace, not subs: `subs` is an exact atom-for-atom map (MatrixElement
    # -> MatrixElement or 0), with none of subs' pattern-matching or assumption
    # re-derivation needed, and subs was the dominant cost of code generation
    # at higher orders (profiled: ~50s of an 85s order-9 run).
    return [M_shift(n, order, symbols, M_dict, source_order=source_order).xreplace(subs)
            for n in M_dict]


def generate_M_shift_operators(order, symbols, M_dict, source_order=0):
    """
    generate_M_shift_operators(order, symbols, index_dict):

    Generates multipole shifting operators up to order.

    Input:
    order, int:
        Maximum order of multipole expansion

    symbols, list:
        List of sympy symbol type objects which define coordinate labels.

    index_dict:
        Forward mapping dictionary between
        monomials of symbols and array indices, generated by generate_mappings
         or otherwise.

    Output:
    list:
        List of symbolic multipole shifting operators up to order.

    Example:
    >>> order = 1
    >>> x, y, z = sp.symbols('x y z')
    >>> map, _ = generate_mappings(order, [x, y, z])
    >>> generate_M_shift_operators(order, (x, y, z), map)
    [M[0, 0], x*M[0, 0] + M[1, 0], y*M[0, 0] + M[2, 0], z*M[0, 0] + M[3, 0]]
    """
    x, y, z = symbols
    M_operators = []
    for n in M_dict.keys():
        M_operators.append(M_shift(n, order, symbols, M_dict, source_order=source_order))
    return M_operators


def generate_derivs(order, symbols, M_dict, source_order=0, harmonic_derivs=False):
    D = sp.MatrixSymbol("D", Nterms(order), 1)
    derivs = []
    for n in M_dict.keys():
        step = pivot_step(n) if harmonic_derivs else None
        if step is not None:
            k1, k2 = step
            derivs.append(-D[M_dict[k1]] - D[M_dict[k2]])
        else:
            derivs.append(Phi_derivatives(n, symbols))
    return derivs


def generate_L_operators(order, symbols, M_dict, L_dict, source_order=0):
    """
    generate_L_operators(order, symbols, index_dict):

    Generates local expansion operators up to given order.

    Input:
    order, int:
        Maximum order of multipole expansion

    symbols, list:
        List of sympy symbol type objects which define coordinate labels.

    index_dict:
        Forward mapping dictionary between
        monomials of symbols and array indices, generated by generate_mappings
        or otherwise.

    inline_derivs: bool
        Calculate derivatives inline rather than precalculating these.

    Output:
    list:
        List of symbolic local expansion operators up to order.

    Example:
    >>> order = 1
    >>> x, y, z = sp.symbols('x y z')
    >>> map, _ = generate_mappings(order, (x, y, z))
    >>> generate_L_operators(order, (x, y, z), map)
    [M[0, 0]/R - 1.0*x*M[1, 0]/R**3 - 1.0*y*M[2, 0]/R**3 - 1.0*z*M[3, 0]/R**3,
    -1.0*x*M[0, 0]/R**3, -1.0*y*M[0, 0]/R**3, -1.0*z*M[0, 0]/R**3]
    """
    x, y, z = symbols
    L_operators = []
    for n in L_dict.keys():
        L_operators.append(L(n, order, symbols, M_dict, source_order=source_order, eval_derivs=False))

    return L_operators


