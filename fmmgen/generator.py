def generate_M2P_operators(
    order,
    symbols,
    M_dict,
    potential=True,
    field=True,
    source_order=0,
    harmonic_derivs=False,
):
    """
    generate_M2L_operators(order, symbols, index_dict)

    Generates potential and field calculation operators for the
    Barnes-Hut method up to order.
    """
    x, y, z = symbols
    R = sp.sqrt(x**2 + y**2 + z**2)

    terms = []

    # Phi_derivatives returns expressions in the atomic symbol Rinv, so the radial
    # dependence must be restored in terms of x, y, z before differentiating -
    # otherwise sp.diff treats Rinv as a constant and the field is wrong.
    V = L((0, 0, 0), order, symbols, M_dict, source_order=source_order, eval_derivs=True).subs(sp.Symbol("Rinv"), 1 / R)
    if potential:
        terms.append(V.subs(1 / R, "Rinv"))

    if field:
        Fx = -sp.diff(V, x).subs(1 / R, "Rinv")
        Fy = -sp.diff(V, y).subs(1 / R, "Rinv")
        Fz = -sp.diff(V, z).subs(1 / R, "Rinv")
        terms.append(Fx)
        terms.append(Fy)
        terms.append(Fz)

    return terms


def generate_L2P_operators(order, symbols, L_dict, potential=True, field=True):
    """
    generate_L2P_operators(order, symbols, index_dict):

    Generates potential and field calculation operators for the Fast
    Multipole Method up to order.

    Input:
    order, int:
        Maximum order of multipole expansion

    symbols, list:
        List of sympy symbol type objects which define coordinate labels.

    index_dict:
        Forward mapping dictionary between monomials of symbols and array
        indices, generated by generate_mappings or otherwise.

    Output:
    list:
        List of symbolic field calculation operators from local expansions up to
        order.

    Example:
    >>> order = 1
    >>> x, y, z = sp.symbols('x y z')
    >>> map, _ = generate_mappings(order, (x, y, z))
    >>> generate_L2P_operators(order, (x, y, z), map)
    [x*L[1, 0] + y*L[2, 0] + z*L[3, 0] + L[0, 0], -L[1, 0], -L[2, 0], -L[3, 0]]
    """
    x, y, z = symbols

    terms = []

    if potential:
        V = phi_deriv(order, symbols, L_dict, deriv=(0, 0, 0))
        terms.append(V)

    if field:
        Fx = -phi_deriv(order, symbols, L_dict, deriv=(1, 0, 0))
        Fy = -phi_deriv(order, symbols, L_dict, deriv=(0, 1, 0))
        Fz = -phi_deriv(order, symbols, L_dict, deriv=(0, 0, 1))
        terms.append(Fx)
        terms.append(Fy)
        terms.append(Fz)
    return terms


def generate_P2P_operators(symbols, M_dict, potential=True, field=True, source_order=0):
    order = source_order
    M_dict, _ = generate_mappings(source_order, symbols, "grevlex", source_order=source_order)
    x, y, z = sp.symbols("x y z")
    R = sp.sqrt(x**2 + y**2 + z**2)

    S_map, _ = generate_mappings(source_order, [x, y, z], key="grevlex", source_order=source_order)
    # print('S_map = {}'.format(S_map))

    M = sp.MatrixSymbol("M", Nterms(order), 1)
    S = sp.MatrixSymbol("S", Nterms(order), 1)

    subsdict = {M[i]: 0 for i in range(Nterms(order))}

    for key in S_map.keys():
        subsdict[M[M_dict[key]]] = S[M_dict[key]]

    # As in generate_M2P_operators: restore the radial dependence in terms of
    # x, y, z before differentiating, since Phi_derivatives emits atomic Rinv.
    V = L((0, 0, 0), order, symbols, M_dict, source_order=source_order).subs(sp.Symbol("Rinv"), 1 / R).subs(subsdict)

    terms = []
    # Note: R must be substituted late for correct derivatives!
    if potential:
        terms.append(V.subs(1 / R, "Rinv"))

    if field:
        Fx = -sp.diff(V, x).subs(1 / R, "Rinv")
        Fy = -sp.diff(V, y).subs(1 / R, "Rinv")
        Fz = -sp.diff(V, z).subs(1 / R, "Rinv")
        terms.append(Fx)
        terms.append(Fy)
        terms.append(Fz)
    return terms


def generate_P2P_operators_planar(symbols, M_dict, potential=True, field=True,
                                  source_order=0, ops=None):
    """
    Planar P2P: both particles of the pair confined to z=0.

    Unlike every other planar operator, there is no array to lift or restrict
    here -- P2P reads the caller's raw source array directly, and that array's
    size is fixed by source_order alone, unrelated to position dimensionality
    (a planar dipole still has 3 moment components). So this is nothing more
    than the ordinary z=0 substitution applied to the already-built,
    already-differentiated expressions.

    The output stays the SAME SIZE as the general P2P (matching the single,
    variant-independent FMMGEN_OUTPUTSIZE the driver indexes every operator's
    output by) -- Fz is NOT dropped, unlike the temptation to do so. It is
    identically zero only at source_order=0 (a monopole's potential is even
    in z, so its z-derivative vanishes at z=0); at source_order=1 a dipole's
    own muz component keeps Fz genuinely nonzero even for two in-plane
    particles, exactly as for L2P/M2P's n_z=1 shell (verified: see
    tests/test_planar.py's P2P case). Substituting z=0 still earns its keep
    by simplifying R (loses its z**2 term entirely, standard sympy
    simplification, no special-casing needed) and cascading through
    whatever CSE finds in the surviving Fx/Fy/(Fz) formulas.
    """
    if ops is None:
        ops = generate_P2P_operators(symbols, M_dict, potential=potential,
                                     field=field, source_order=source_order)
    z = symbols[2]
    return [sp.sympify(e).xreplace({z: 0}) for e in ops]


# --------------------------------------------------------------------------
# Compressed (harmonic / trace-free) operator variants
#
# Each is the uncompressed operator with the transformations of
# fmmgen.harmonic applied to its input and output arrays. Nothing is
# rederived; the operators are linear in their expansion arrays, so
# substitution and projection suffice, and correctness follows from the
# identity H = Dec H[keep,keep] Dec^T verified in tests/test_harmonic.py.
#
# The multipole and local arrays need SEPARATE retained sets. They coincide
# only at source_order = 0; for a source of order s the multipole covers
# s <= |n| <= p while the local covers |m| <= p - s, so keep_M and keep_L are
# different index sets of different sizes. Passing one for both was what
# previously limited this to source_order = 0.
#
# source_order >= 2 is still rejected, for a different and real reason: at
# degree k the retained count is 2k+1 against (k+1)(k+2)/2 monomials, equal
# only for k <= 1. So a monopole or dipole source shell survives compression
# untouched (1 = 1, 3 = 3) and generate_S2M_operators' assumption that the
# shell indexes directly into the caller's S array still holds, whereas a
# quadrupole's six components compress to five -- physically right, since the
# trace of a quadrupole moment contributes nothing to a Laplace field, but it
# makes S2M a genuine projection and changes the caller's ABI.
# --------------------------------------------------------------------------

def _reject_source_order(source_order):
    if source_order > 1:
        raise NotImplementedError(
            "compressed operators support source_order 0 or 1; got "
            f"{source_order}. At degree >= 2 the source shell itself "
            "compresses (6 monomials -> 5 retained at s=2), so S2M would have "
            "to project the caller's moment array. Use compress=False."
        )


def _keep_sets(order, symbols, M_dict, L_dict, source_order):
    """Retained index sets and decompression maps for the two arrays."""
    keep_M, _ = keep_mappings(order, symbols, source_order=source_order)
    keep_L, _ = keep_mappings(order - source_order, symbols, source_order=0)
    return keep_M, keep_L, decompress_for(M_dict), decompress_for(L_dict)


def generate_S2M_operators_compressed(order, symbols, M_dict, keep_M, source_order=0,
                                      dec_M=None, ops=None):
    _reject_source_order(source_order)
    if ops is None:
        ops = generate_S2M_operators(order, symbols, M_dict, source_order=source_order)
    return project_multipole(ops, M_dict, keep_M, dec_M or decompress_for(M_dict))


def generate_M_shift_operators_compressed(order, symbols, M_dict, keep_M, source_order=0,
                                          dec_M=None, ops=None):
    _reject_source_order(source_order)
    dec_M = dec_M or decompress_for(M_dict)
    if ops is None:
        ops = generate_M_shift_operators(order, symbols, M_dict, source_order=source_order)
    subs = lift_multipole_subs("M", Nterms(order), len(keep_M), M_dict, keep_M)
    ops = [expr.xreplace(subs) for expr in ops]
    return project_multipole(ops, M_dict, keep_M, dec_M)


def generate_L_operators_compressed(order, symbols, M_dict, L_dict, keep_M, keep_L,
                                    source_order=0, ops=None):
    _reject_source_order(source_order)
    if ops is None:
        ops = generate_L_operators(order, symbols, M_dict, L_dict, source_order=source_order)
    subs = lift_multipole_subs("M", Nterms(order), len(keep_M), M_dict, keep_M)
    ops = [expr.xreplace(subs) for expr in ops]
    return restrict_local(ops, L_dict, keep_L)


def generate_L_shift_operators_compressed(order, symbols, L_dict, keep_L, source_order=0,
                                          dec_L=None, ops=None):
    _reject_source_order(source_order)
    dec_L = dec_L or decompress_for(L_dict)
    if ops is None:
        ops = generate_L_shift_operators(order, symbols, L_dict, source_order=source_order)
    subs = expand_local_subs("L", Nterms(order), len(keep_L), L_dict, keep_L, dec_L)
    ops = [expr.xreplace(subs) for expr in ops]
    return restrict_local(ops, L_dict, keep_L)


def generate_L2P_operators_compressed(order, symbols, L_dict, keep_L, potential=True,
                                      field=True, dec_L=None, ops=None):
    dec_L = dec_L or decompress_for(L_dict)
    if ops is None:
        ops = generate_L2P_operators(order, symbols, L_dict, potential=potential, field=field)
    subs = expand_local_subs("L", Nterms(order), len(keep_L), L_dict, keep_L, dec_L)
    return [expr.xreplace(subs) for expr in ops]


def generate_M2P_operators_compressed(
    order, symbols, M_dict, keep_M, potential=True, field=True,
    source_order=0, harmonic_derivs=False, ops=None,
):
    _reject_source_order(source_order)
    if ops is None:
        ops = generate_M2P_operators(
            order, symbols, M_dict, potential=potential, field=field,
            source_order=source_order, harmonic_derivs=harmonic_derivs,
        )
    subs = lift_multipole_subs("M", Nterms(order), len(keep_M), M_dict, keep_M)
    return [expr.xreplace(subs) for expr in ops]


def generate_M2L_compressed(order, symbols, M_dict, L_dict, keep_M, keep_L,
                            source_order=0, harmonic_derivs=False, ops=None):
    """
    Compressed M2L, returning (derivs, L_operators) with a compact D array.

    The compressed contraction only ever references derivatives D_{i+j} with
    i, j retained, hence with third index <= 2, which is O(p^2) of the
    O(p^3) entries the uncompressed operator needs. Emitting the full
    derivative array would hand back a good part of the saving, so the used
    entries are collected and reindexed into a dense array.

    Ordering is inherited from the uncompressed index map, which is what makes
    harmonic_derivs still valid here: pivot_step targets have the same total
    degree and a lower z index, so under grevlex on [z, y, x] they keep an
    earlier slot than the entry that depends on them. Where a target falls
    outside the used set the derivative is computed directly instead.
    """
    _reject_source_order(source_order)

    L_ops = generate_L_operators_compressed(
        order, symbols, M_dict, L_dict, keep_M, keep_L, source_order=source_order, ops=ops
    )

    D_full = sp.MatrixSymbol("D", Nterms(order), 1)
    used = sorted(
        {
            a.i
            for expr in L_ops
            for a in expr.atoms(sp.matrices.expressions.matexpr.MatrixElement)
            if a.parent.name == "D"
        }
    )
    remap = {old: new for new, old in enumerate(used)}
    D = sp.MatrixSymbol("D", len(used), 1)
    L_ops = [expr.xreplace({D_full[o]: D[n] for o, n in remap.items()}) for expr in L_ops]

    rmap = {idx: n for n, idx in M_dict.items()}
    derivs = []
    for old in used:
        n = rmap[old]
        step = pivot_step(n) if harmonic_derivs else None
        if step is not None and all(k in M_dict and M_dict[k] in remap for k in step):
            k1, k2 = step
            derivs.append(-D[remap[M_dict[k1]]] - D[remap[M_dict[k2]]])
        else:
            derivs.append(Phi_derivatives(n, symbols))

    return derivs, L_ops


# --------------------------------------------------------------------------
# Planar (2D-plane) operator variants
#
# Sources (and, for the local array, evaluation points) confined to z = 0,
# with moment VECTORS that remain full 3D -- e.g. an atomistic magnetic
# dipole in a monolayer still has a (mux, muy, muz) moment even though its
# position has no z. This is a positional degeneracy, not a change of PDE:
# the kernel is still 1/R, not the 2D Laplace log(r) kernel that would apply
# if sources were translationally invariant along z instead.
#
# Every inter-cell and cell-to-particle displacement is a difference of two
# z=0 coordinates, hence identically zero, so z (equivalently every
# translation symbol -- expansions.py always calls it z regardless of its
# physical role as a source-to-centre, cell-to-cell or centre-to-target
# vector) can be set to 0 in each already-built uncompressed operator before
# printing. Differentiation w.r.t. z, where it happens (M2P, P2P's own
# internal use of sp.diff), always happens before this substitution is
# applied, since it acts on the functions' *return values*.
#
# The multipole array's retained set is n_z <= source_order: a source's own
# moment shell (|n| = source_order) is the only place z-content can enter --
# M_shift's recursion only ever reads an input coefficient at the SAME n_z it
# writes, because every displacement power is dz**k with dz = 0, killing
# every k >= 1 -- so n_z can never exceed what the shell itself started with.
# This is verified by direct construction in tests/test_planar.py, not just
# asserted here.
#
# The local array's retained set is n_z <= 1 if the field is wanted, else
# n_z <= 0: L2P only ever reads L at n_z = 0 for the potential/Fx/Fy (the
# evaluation point's z-offset is 0, killing any n_z >= 1 term) and at n_z = 1
# for Fz (one extra z-derivative before evaluating at dz = 0). This is a
# property of what L2P asks for, independent of source_order -- unlike the
# multipole array, more distant sources never change what a local expansion
# needs to have been evaluated to.
#
# Excluded multipole entries are PROVABLY ZERO (not, as in the harmonic case,
# expressible as a linear combination of retained ones), and excluded local
# entries are simply never read by a correctly z=0-evaluating pipeline. So
# unlike the compressed variants, planar needs only two of harmonic.py's four
# mechanical transforms: lift_multipole_subs (zero-fill an excluded input
# slot) and restrict_local (take the retained subset of an output list). It
# never needs project_multipole or expand_local_subs, which exist specifically
# to reconstruct excluded entries that are NOT zero.
# --------------------------------------------------------------------------

def _planar_keep(order, symbols, source_order, max_nz):
    """Retained indices {n : |n| <= order, n_z <= max_nz}, contiguously
    reindexed in the same relative order as generate_mappings.

    Deliberately independent of fmmgen.harmonic.keep_mappings, which fixes
    max_nz = 1 unconditionally (the trace-free relation does not depend on
    source_order). Here max_nz is source_order for the multipole array, or
    0/1 for the local array depending on whether the field is wanted -- see
    the module-level note above.
    """
    if order < 0:
        return {}
    full, _ = generate_mappings(order, symbols, source_order=source_order)
    kept = [n for n in full if n[2] <= max_nz]
    return {n: i for i, n in enumerate(kept)}


def Nterms_planar(order, max_nz):
    """Closed-form count of |_planar_keep(order, symbols, 0, max_nz)|: the
    number of 3-variable monomials with total degree <= order and z-degree
    <= max_nz. For fixed n_z = j, the (n_x, n_y) pairs range over total
    degree <= order - j, a plane count of (order-j+1)(order-j+2)/2.

    >>> [Nterms_planar(p, p) for p in range(4)]  # max_nz >= order: no restriction
    [1, 4, 10, 20]
    >>> [Nterms_planar(p, 1) for p in range(1, 4)]
    [4, 9, 16]
    """
    if order < 0:
        return 0
    max_nz = min(max_nz, order)
    return sum((order - j + 1) * (order - j + 2) // 2 for j in range(max_nz + 1))


def Nterms_planar_M(order, source_order):
    """Closed-form count of |_planar_keep(order, symbols, source_order,
    max_nz=source_order)|: the planar multipole array's retained size,
    {n : source_order <= |n| <= order, n_z <= source_order}.

    Nterms_planar (no lower bound) is not this function with an extra term
    subtracted off -- the multipole array's own lower bound (a source has no
    multipole below its own order) interacts with the n_z <= source_order
    cutoff, since a fixed n_z = j shell's (n_x, n_y) pairs must range over
    source_order - j <= n_x + n_y <= order - j, not 0 <= n_x + n_y <= order - j.
    Both endpoints are pinned by the same source_order, so this needed its
    own derivation rather than reusing Nterms_planar with a subtraction.

    >>> [Nterms_planar_M(p, 1) for p in range(1, 5)]  # matches len(_planar_keep(p, symbols, 1, 1))
    [3, 8, 15, 24]
    """
    if order < source_order:
        return 0
    s = source_order

    def tri(k):
        return (k + 1) * (k + 2) // 2 if k >= 0 else 0

    return sum(tri(order - j) - tri(s - j - 1) for j in range(s + 1))


def _keep_sets_planar(order, symbols, source_order, field=True):
    """Retained index sets for the planar multipole and local arrays.

    Mirrors _keep_sets' asymmetry (the multipole spans s <= |n| <= p while
    the local spans |m| <= p - s) but with planar's own, source_order- and
    field-dependent cutoffs rather than harmonic's fixed n_z <= 1.
    """
    keep_M = _planar_keep(order, symbols, source_order, max_nz=source_order)
    keep_L = _planar_keep(order - source_order, symbols, 0, max_nz=1 if field else 0)
    return keep_M, keep_L


